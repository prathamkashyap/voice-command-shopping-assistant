import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const publicRoot = fileURLToPath(new URL('../public/', import.meta.url));

async function walk(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (entry.isFile() && !entry.name.startsWith('.')) files.push(path);
  }
  return files;
}

export async function renderPrecacheManifest() {
  const paths = (await walk(publicRoot)).map(path => path.slice(publicRoot.length))
    .filter(path => path !== 'precache-manifest.js').sort();
  const hash = createHash('sha256');
  for (const path of paths) {
    const contentHash = createHash('sha256').update(await readFile(join(publicRoot, path))).digest('hex');
    hash.update(path + '\0' + contentHash + '\n');
  }
  const assets = paths.filter(path => path !== 'sw.js').map(path => '/' + path);
  const revision = hash.digest('hex').slice(0, 20);
  return '// Generated by node scripts/update-precache.mjs\n' +
    `export const CACHE_NAME = 'shopping-assistant-shell-${revision}';\n` +
    `export const STATIC_ASSETS = ${JSON.stringify(assets, null, 2)};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(join(publicRoot, 'precache-manifest.js'), await renderPrecacheManifest());
}
